"""Join ISSUE_CATALOG codes to WMO/ICAO/IWXXM source attribution (EV-040 / F15).

Loads packaged ``catalog_attribution.json`` (generated by ``make catalog-regen`` from
``PROVENANCE_MAP.json``). Citations and URLs only — no copyrighted Annex prose.

Additive EV-061 / #1014 fields (``family``, ``source_type``, ``status``, …) are derived
for the HTTP catalog so operator hrefs stay verified landings
(``D-S071-links-resolve``).

Additive EV-062 / #1017 fields: ``source_locator``, ``source_access``.
"""

from __future__ import annotations

import json
import re
from functools import lru_cache
from pathlib import Path
from typing import Any, cast

from tac_validate.issue_catalog_meta import source_access_for, source_locator_for

_DATA = Path(__file__).resolve().parent / "data" / "catalog_attribution.json"

# Notes appended to operator-facing source_attribution (EV-048) — omit planning ids.
_INTERNAL_DOC_REF_IN_NOTE = re.compile(
    r"(?:\[Corpus:|\bADR-\d+\b|\bEV-\d+\b|\bS0\d+\b|\bTC-[A-Z0-9-]+\b|"
    r"\bE\d{2}-\d+\b|(?<!\w)#\d{3,}\b|\bF\d+\b|docs/sessions/|docs/feature-list)"
)

# Crawl date for operator-verified HTTP landings (EV-061 catalog crawl; EV-062 retarget).
_LAST_VERIFIED = "2026-08-20"

# Public companions preferred over sole ICAO storefront when lawful free cite exists.
_PUBLIC_COMPANIONS: dict[str, str] = {
    "icao-eur-doc-014": (
        "https://www.icao.int/sites/default/files/EURNAT/Documents/EUR%20and%20Nat%20Docs/"
        "EUR%20Documents/EUR%20Documents/014%20-%20EUR%20SIGMET%20and%20AIRMET%20Guide/"
        "EUR-Doc-14-EN-5th-Ed-2023-rev-Dec23-clean.pdf"
    ),
}


@lru_cache(maxsize=1)
def _load() -> dict[str, dict[str, Any]]:
    if not _DATA.is_file():
        return {}
    try:
        loaded: object = json.loads(_DATA.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError):
        return {}
    if not isinstance(loaded, dict):
        return {}
    payload = cast(dict[str, object], loaded)
    codes_obj = payload.get("codes")
    if not isinstance(codes_obj, dict):
        return {}
    codes = cast(dict[object, object], codes_obj)
    out: dict[str, dict[str, Any]] = {}
    for key_obj, value_obj in codes.items():
        if not isinstance(value_obj, dict):
            continue
        out[str(key_obj)] = cast(dict[str, Any], value_obj)
    return out


def _source_type(source_id: str | None, source_url: str | None) -> str | None:
    """Map provenance to three-tier source policy (``D-S071-links-resolve``)."""
    blob = f"{source_id or ''} {source_url or ''}".lower()
    if "wmo-im/iwxxm" in blob or "releasenotes-iwxxm" in blob:
        return "tier1"
    if "codes.wmo.int" in blob or "codes-wmo" in blob:
        return "tier3"
    if source_url and source_url.startswith(("http://", "https://")):
        return "tier2"
    return None


def _operator_status(source_url: str | None, raw_status: str | None) -> str | None:
    """Operator catalog status: verified landings vs semantic-only / legacy."""
    if source_url and source_url.startswith(("http://", "https://")):
        return "verified"
    if source_url and source_url.startswith("vendor:"):
        return "semantic_only"
    if raw_status in {"N/A", "gap"}:
        return "semantic_only"
    return None


def _semantic_identifier(source_id: str | None, source_url: str | None) -> str | None:
    """Keep Codes Registry concept paths as semantic aliases when href is a landing."""
    if source_id == "codes-wmo-int":
        return "https://codes.wmo.int/"
    if source_url and "codes.wmo.int/ui/resources" in source_url:
        return "https://codes.wmo.int/"
    return None


def attribution_for(code: str) -> dict[str, str | None]:
    """
    Return source attribution fields for a registry code.

    Parameters
    ----------
    code :
        Stable SCREAMING_SNAKE issue code.

    Returns
    -------
    dict[str, str | None]
        Keys ``source_id``, ``source_url``, ``source_attribution``, plus additive
        ``family``, ``source_type``, ``status``, ``semantic_identifier``,
        ``last_verified``, ``replacement_url``, ``source_locator``,
        ``source_access`` (may be None).
    """
    row = _load().get(code) or {}
    source_id_obj: object = row.get("source_id")
    source_url_obj: object = row.get("source_url")
    status_obj: object = row.get("status")
    note_obj: object = row.get("note")
    source_id = source_id_obj if isinstance(source_id_obj, str) else None
    source_url = source_url_obj if isinstance(source_url_obj, str) else None
    raw_status = status_obj if isinstance(status_obj, str) else None
    note = note_obj if isinstance(note_obj, str) else None
    replacement_url: str | None = None
    # Prefer public companion as primary href when provenance is paywall-only Annex 3
    # but a public official companion is recorded for this source family.
    if source_url and "store.icao.int" in source_url and note and "eur doc 014" in note.lower():
        companion = _PUBLIC_COMPANIONS["icao-eur-doc-014"]
        replacement_url = source_url
        source_url = companion
        source_id = source_id or "icao-eur-doc-014"
    parts: list[str] = []
    if source_id:
        parts.append(source_id)
    if raw_status in {"paywall", "gap", "N/A"}:
        parts.append(f"access:{raw_status}")
    # Prefer stable URL in operator-facing attribution; note is secondary.
    if source_url:
        parts.append(source_url)
    if note and not _INTERNAL_DOC_REF_IN_NOTE.search(note):
        parts.append(note)
    attribution = " — ".join(parts) if parts else None
    status = _operator_status(source_url, raw_status)
    locator = source_locator_for(note)
    if locator and raw_status == "paywall" and re.search(r"\bApp\b|\bTable\b|\bA\d", locator):
        if not locator.lower().startswith("icao"):
            locator = f"ICAO Annex 3 {locator}"
    access = source_access_for(
        source_url=source_url,
        raw_status=raw_status if replacement_url is None else "ok",
        operator_status=status,
    )
    # After public swap, primary is the public companion; keep storefront as
    # replacement_url. Force paywall only when the *primary* href is still the store.
    if source_url and "store.icao.int" in source_url:
        access = "paywall"
    elif replacement_url and "store.icao.int" in replacement_url:
        access = "public"
    return {
        "source_id": source_id,
        "source_url": source_url,
        "source_attribution": attribution,
        "family": "lint",
        "source_type": _source_type(source_id, source_url),
        "status": status,
        "semantic_identifier": _semantic_identifier(source_id, source_url),
        "last_verified": _LAST_VERIFIED if status == "verified" else None,
        "replacement_url": replacement_url,
        "source_locator": locator,
        "source_access": access,
    }


__all__ = ["attribution_for"]
